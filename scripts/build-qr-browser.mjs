// Package the installed browser QR encoder as a local ES module. Only static CommonJS
// requires are supported; the browser entry has no Node builtins or dynamic dependencies.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const root = join(import.meta.dirname, '..'), require = createRequire(join(root, 'package.json'));
const ids = new Map(), modules = [];
function collect(path) {
  if (ids.has(path)) return ids.get(path);
  const id = modules.length; ids.set(path, id); modules.push('');
  const resolve = createRequire(path);
  const source = readFileSync(path, 'utf8').replace(/require\(['"]([^'"]+)['"]\)/g, (_, name) => {
    const dependency = resolve.resolve(name);
    if (!dependency.endsWith('.js')) throw new Error('Unsupported browser dependency: ' + name);
    return 'require(' + collect(dependency) + ')';
  });
  modules[id] = '(module, exports, require) => {\n' + source + '\n}';
  return id;
}
const entry = collect(require.resolve('qrcode/lib/browser.js'));
const license = readFileSync(require.resolve('qrcode/license'), 'utf8') + '\n' + readFileSync(require.resolve('dijkstrajs/LICENSE.md'), 'utf8');
const source = '/* Generated by scripts/build-qr-browser.mjs from qrcode ' + require('qrcode/package.json').version + '.\n' + license.replaceAll('*/', '* /') + '\n*/\nconst modules = [\n' + modules.join(',\n') + '\n];\nconst cache = new Map();\nfunction require(id) { if (cache.has(id)) return cache.get(id).exports; const module = { exports: {} }; cache.set(id, module); modules[id](module, module.exports, require); return module.exports; }\nexport default require(' + entry + ');\n';
writeFileSync(join(root, 'public/vendor/qrcode.js'), source);
console.log('Bundled local browser QR encoder (' + modules.length + ' modules).');
